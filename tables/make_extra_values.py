"""Value macros for the coordination, fixed-cage, Zn(CN)2, effective-row and spread checks, read from result files
(no hand-copied numbers).

Sources:
  controls/unbiased_coordination.json   scaffold mean coordination in the unbiased control (S3.4, main text)
  fixed_cage/urk_fixed_cage.json        fixed-cage second-order width of pcu x urk (S2.6, S2.7, Table I)
  zinc_cyanide/zn_branches.json         branch widths of the Zn(CN)2 rigid-unit bands (S5.3, main text)
  counting/eeff_count.json              effective-row counts per S eigenvalue, common primitive cell (S2.7)
  high_symmetry/flat_pairs.csv          unrounded first-order spreads, second implementation (Methods)
Writes extra_values.tex.

  python tables/make_extra_values.py [--root DIR] [--out DIR]     (defaults as for make_tables.py)
"""
import argparse, csv, json, math, os
_ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
_ap.add_argument('--root', default=os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')))
_ap.add_argument('--out')
_a = _ap.parse_args()
ROOT = _a.root
HERE = _a.out or os.path.join(ROOT, 'outputs', 'tables')
os.makedirs(HERE, exist_ok=True)
X = lambda n: json.load(open(os.path.join(ROOT, n), encoding='utf-8'))


def sci(x, sig=2, up=False):
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10 ** e
    m = math.ceil(m * 10 ** (sig - 1)) / 10 ** (sig - 1) if up else round(m, sig - 1)
    if m >= 10:
        m /= 10; e += 1
    ms = f'{m:.{sig - 1}f}'.rstrip('0').rstrip('.') if sig > 1 else f'{m:.0f}'
    return f'{ms}\\times10^{{{e}}}'


M = {}
# unbiased control coordination
uc = X('controls/unbiased_coordination.json'); c = uc['table']['cells']
M['xcHighDualRigid'] = c['dual >=6']['rigid']; M['xcHighDual'] = c['dual >=6']['total']
M['xcHighOtherRigid'] = c['nondual >=6']['rigid']; M['xcHighOther'] = c['nondual >=6']['total']
assert c['dual <6']['rigid'] == 0 and c['nondual <6']['rigid'] == 0
M['xcLowDual'] = c['dual <6']['total']; M['xcLowOther'] = c['nondual <6']['total']
M['xcFisherP'] = f"{uc['table']['fisher_p_dual_vs_nondual_among_high_coordination']:.2f}"
M['xcAtSix'] = uc['coordination_exactly_6_count']
M['xcRows'] = uc['n_rows']
# pcu x urk fixed cage
uk = X('fixed_cage/urk_fixed_cage.json'); a, b = uk['main_40q_seed20261107'], uk['check_400q_seed20261108']
kmin = min(uk['kc_list']); key = [k for k in a['per_kc'] if float(k) == kmin][0]
M['urkNq'] = a['n_drawn']; M['urkNused'] = a['n_used']
M['urkNqLarge'] = b['n_drawn']; M['urkNusedLarge'] = b['n_used']
M['urkCoef'] = f"{a['per_kc'][key]['max_width_over_kc2']:.2f}"
M['urkCoefLarge'] = f"{b['per_kc'][key]['max_width_over_kc2']:.2f}"
M['urkSlope'] = f"{min(a['fit']['max_branch']['slope'], b['fit']['max_branch']['slope']):.2f}"
M['urkKcMin'] = f'{kmin:g}'; M['urkKcMax'] = f'{max(uk["kc_list"]):g}'
M['urkGap'] = '0.1'
assert 'gap_F>=0.1' in uk['definition']
# Zn(CN)2 branches
zn = X('zinc_cyanide/zn_branches.json')['rigid_units']
M['znNbranch'] = zn['n_branches']
M['znBranchWidthMin'] = f"{zn['width_min']:.1f}"; M['znBranchWidthMax'] = f"{zn['width_max']:.1f}"
M['znOnsiteWidth'] = sci(zn['contact_onsite_branch_width_max'], 1, up=True)
# effective-row count, she-d x she level at 8/3
ee = X('counting/eeff_count.json')
lev = [l for l in ee['she-d ⊗ she']['levels'] if abs(l['a'] - 8 / 3) < 1e-4][0]
M['xeSheN'] = lev['n']; M['xeSheE'] = max(lev['E_eff']); M['xeSheDim'] = lev['dim']
# unrounded spreads, second implementation
R = list(csv.DictReader(open(os.path.join(ROOT, 'high_symmetry', 'flat_pairs.csv'), encoding='utf-8-sig')))
fl = [float(r['spread_rel']) for r in R if r['original_class'] == 'exact']
nr = [float(r['spread_rel']) for r in R if r['original_class'] == 'near']
assert len(fl) == 10
M['xfFlatMin'] = sci(min(fl)); M['xfFlatMax'] = sci(max(fl), up=True); M['xfNearMin'] = f'{math.floor(min(nr) * 1000) / 1000:.3f}'

with open(os.path.join(HERE, 'extra_values.tex'), 'w', encoding='utf-8') as f:
    f.write('% generated by make_extra_values.py from the result files; do not edit\n')
    for k, v in M.items():
        f.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')
print(M)
